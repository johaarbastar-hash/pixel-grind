// char code -> atlas slot (-1 = blank); arrows live above ASCII
const SLOT = new Int16Array(128).fill(-1);
const EXTRA = new Map();
const ORDER = Object.keys(GLYPHS);
ORDER.forEach((ch, i) => {
  const code = ch.charCodeAt(0);
  if (code < 128) SLOT[code] = i;
  else EXTRA.set(code, i);
});
// lower-case letters map to upper-case, except x (multiply sign)
for (let c = 97; c <= 122; c++) {
  if (c !== 120) SLOT[c] = SLOT[c - 32];
}

let whiteAtlas = null;
const tinted = new Map();

function buildWhiteAtlas() {
  const c = document.createElement('canvas');
  c.width = ORDER.length * CHAR_W;
  c.height = CHAR_H;
  const g = c.getContext('2d');
  g.fillStyle = '#fff';
  ORDER.forEach((ch, i) => {
    GLYPHS[ch].forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') g.fillRect(i * CHAR_W + x, y, 1, 1);
    });
  });
  return c;
}

function atlasFor(color) {
  let a = tinted.get(color);
  if (a) return a;
  if (!whiteAtlas) whiteAtlas = buildWhiteAtlas();
  a = document.createElement('canvas');
  a.width = whiteAtlas.width;
  a.height = whiteAtlas.height;
  const g = a.getContext('2d');
  g.drawImage(whiteAtlas, 0, 0);
  g.globalCompositeOperation = 'source-in';
  g.fillStyle = color;
  g.fillRect(0, 0, a.width, a.height);
  tinted.set(color, a);
  return a;
}

export function textWidth(text, scale = 1) {
  return text.length === 0 ? 0 : (text.length * CHAR_W - 1) * scale;
}

function drawRaw(g, text, x, y, atlas, scale) {
  const size = CHAR_W * scale;
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    const slot = code < 128 ? SLOT[code] : EXTRA.get(code) ?? -1;
    if (slot >= 0) g.drawImage(atlas, slot * CHAR_W, 0, CHAR_W, CHAR_H, x + i * size, y, size, size);
  }
}

// opts: { align: 'left' | 'center' | 'right', scale: 1, shadow: color }
export function drawText(g, text, x, y, color, opts) {
  const scale = (opts && opts.scale) || 1;
  const align = opts && opts.align;
  let left = x;
  if (align === 'center') left = x - Math.floor(textWidth(text, scale) / 2);
  else if (align === 'right') left = x - textWidth(text, scale);
  left = Math.round(left);
  y = Math.round(y);
  if (opts && opts.shadow) drawRaw(g, text, left + scale, y + scale, atlasFor(opts.shadow), scale);
  drawRaw(g, text, left, y, atlasFor(color), scale);
}
